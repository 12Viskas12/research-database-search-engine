const ERROR_PATTERNS_UK = [
  [/^Term: 1 to (\d+) days$/, (m) => `Термін: від 1 до ${m[1]} днів`],
  [/^Monthly limit reached \((\d+)\)\. Resets on the 1st at 00:00 UTC\.$/, (m) => `Місячний ліміт вичерпано (${m[1]}). Скидання 1-го числа о 00:00 UTC.`],
  [/^At most (\d+) values at once$/, (m) => `Не більше ${m[1]} значень за раз`],
  [/^This file is already uploaded: (.*) \(id (\d+)\)$/, (m) => `Такий файл уже завантажено: ${m[1]} (id ${m[2]})`],
];

let LANG = "uk";

function detectLang() {
  try {
    const saved = localStorage.getItem("lang");
    if (saved === "uk" || saved === "en") return saved;
  } catch {
    return "uk";
  }
  return (navigator.language || "").toLowerCase().startsWith("en") ? "en" : "uk";
}

function setLang(lang) {
  LANG = lang;
  try {
    localStorage.setItem("lang", lang);
  } catch {
    LANG = lang;
  }
  document.documentElement.lang = lang;
}

function t(key, vars) {
  let text = (DICT[LANG] && DICT[LANG][key]) || DICT.en[key] || key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

function errorText(message) {
  if (LANG !== "uk") return message;
  if (ERRORS_UK[message]) return ERRORS_UK[message];
  for (const [re, fn] of ERROR_PATTERNS_UK) {
    const m = message.match(re);
    if (m) return fn(m);
  }
  return message;
}

function applyStatic() {
  document.querySelectorAll("[data-i18n]").forEach((n) => {
    n.textContent = t(n.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((n) => {
    n.placeholder = t(n.dataset.i18nPh);
  });
  document.querySelectorAll("[data-lang]").forEach((n) => {
    n.classList.toggle("active", n.dataset.lang === LANG);
  });
}
